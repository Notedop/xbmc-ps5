#!/usr/bin/env python3
"""Validate selected installed audio decoders and optionally stage them.

Installed lib*.so companions are staged beside the primary and listed in a
generated ps5-auxiliaries.list, which authorizes the PS5 loader to dlopen
exactly those helpers from that directory. Every staged ELF must satisfy the
loader's constraints: x86-64 ET_DYN, no PT_TLS, no DT_NEEDED and only
RELATIVE/64/GLOB_DAT/JUMP_SLOT relocations.
"""

import argparse
from pathlib import Path
import re
import shutil
import struct
import xml.etree.ElementTree as ET

MANIFEST = "ps5-auxiliaries.list"
ALLOWED_RELOCATIONS = {1: "64", 6: "GLOB_DAT", 7: "JUMP_SLOT", 8: "RELATIVE"}
BASENAME = re.compile(r"[A-Za-z0-9_+-][A-Za-z0-9._+-]{0,127}")


def elf_problems(path):
    data = path.read_bytes()
    if len(data) < 64 or data[:4] != b"\x7fELF" or data[4] != 2 or data[5] != 1:
        return ["not a little-endian ELF64 file"]
    e_type, e_machine = struct.unpack_from("<HH", data, 16)
    e_phoff, e_shoff = struct.unpack_from("<QQ", data, 32)
    e_phentsize, e_phnum, e_shentsize, e_shnum = struct.unpack_from("<HHHH", data, 54)
    problems = []
    if e_type != 3 or e_machine != 62:
        problems.append("not an x86-64 shared object")
    for index in range(e_phnum):
        (p_type,) = struct.unpack_from("<I", data, e_phoff + index * e_phentsize)
        if p_type == 7:
            problems.append("contains PT_TLS")
    if not e_shnum:
        return problems + ["has no section headers to inspect"]
    sections = [struct.unpack_from("<IIQQQQIIQQ", data, e_shoff + i * e_shentsize)
                for i in range(e_shnum)]
    for _, sh_type, _, _, offset, size, _, _, _, entsize in sections:
        if sh_type == 6:  # SHT_DYNAMIC
            for entry in range(size // 16):
                (tag,) = struct.unpack_from("<q", data, offset + entry * 16)
                if tag == 1:
                    problems.append("has DT_NEEDED dependencies")
                    break
                if tag == 0:
                    break
        elif sh_type == 4:  # SHT_RELA
            for entry in range(size // (entsize or 24)):
                (info,) = struct.unpack_from("<Q", data, offset + entry * 24 + 8)
                kind = info & 0xFFFFFFFF
                if kind not in ALLOWED_RELOCATIONS:
                    problems.append(f"unsupported relocation type {kind}")
                    break
    return problems


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--prefix", type=Path, required=True)
parser.add_argument("--destination", type=Path)
parser.add_argument("addons", nargs="+")
args = parser.parse_args()
selected = []
for addon in args.addons:
    if not re.fullmatch(r"audiodecoder\.[a-z0-9]+", addon):
        parser.error(f"invalid audio decoder ID: {addon}")
    data = args.prefix / "share/kodi/addons" / addon
    manifest = data / "addon.xml"
    if not manifest.is_file():
        parser.error(f"missing manifest: {manifest}")
    root = ET.parse(manifest).getroot()
    extension = root.find("./extension[@point='kodi.audiodecoder']")
    library = extension.get("library_freebsd", "") if extension is not None else ""
    if root.get("id") != addon or not library or Path(library).name != library:
        parser.error(f"invalid FreeBSD audio decoder manifest: {manifest}")
    if not BASENAME.fullmatch(library):
        parser.error(f"unsupported primary basename: {library}")
    if (data / MANIFEST).exists():
        parser.error(f"installed data must not provide {MANIFEST}: {data}")
    binary = args.prefix / "lib/kodi/addons" / addon / library
    if not binary.is_file():
        parser.error(f"missing decoder binary: {binary}")
    companions = sorted(p for p in binary.parent.glob("lib*.so") if not p.is_symlink())
    for elf in [binary, *companions]:
        if elf != binary and not BASENAME.fullmatch(elf.name):
            parser.error(f"unsupported helper basename: {elf}")
        problems = elf_problems(elf)
        if problems:
            parser.error(f"{elf} is not loadable on PS5: {'; '.join(problems)}")
    selected.append((addon, data, library, binary, companions))

for addon, data, library, binary, companions in selected:
    if args.destination:
        destination = args.destination / "addons" / addon
        shutil.copytree(data, destination, dirs_exist_ok=True)
        shutil.copy2(binary, destination / library)
        for companion in companions:
            shutil.copy2(companion, destination / companion.name)
        if companions:
            lines = ["# Generated by tools/ps5/stage-audio-decoders.py", "format 1",
                     f"primary {library}", *(f"helper {c.name}" for c in companions)]
            (destination / MANIFEST).write_text("\n".join(lines) + "\n", encoding="ascii")
    else:
        print(binary)
        for companion in companions:
            print(companion)
