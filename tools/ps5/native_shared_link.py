#!/usr/bin/env python3
"""Convert an LLD-linked shared library into a native PS5 shared module.

Link with native-shared.ld, --hash-style=sysv, -z now, -z max-page-size=0x4000,
-init module_start and -fini module_stop. Each DT_NEEDED must have a provider
manifest generated by native_runtime_sdk.py. No Kodi executable is an input.

This first shared profile supports functions, data, GOT/absolute relocations,
large BSS and eager imports. Module lifecycle routines must be supplied by the
library. Constructor/destructor arrays require native_module_crt.cpp. Native TLS
and thread-local destructor unloading are not qualified and fail explicitly.
This is not a complete C++ runtime or a console-accepted candidate.
SPDX-License-Identifier: GPL-3.0-or-later
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import struct

from native_c_link import (
    Elf, NOTE_HEADER, PAGE, PHDR, RELA, SYM, align, cstring, hash_table,
    module_identity, nid, require,
)
from native_runtime_sdk import validate_stub

DYNAMIC = struct.Struct("<QQ")
SUPPORTED_RELOCATIONS = {1: 8, 6: 8, 8: 8}
LIFECYCLE_MARKER = b"PS5-NATIVE-CRT\0\1\0"
PROCESS_LIFETIME_MARKER = b"PS5-NATIVE-LIFE\1\0"


def encode_id(value):
    alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+-"
    require(0 <= value < 65536, "native library/module ID overflow")
    result = ""
    while value or not result:
        result = alphabet[value % 64] + result
        value //= 64
    return result


def dynamic_entries(image):
    section = image.sections.get(".dynamic")
    require(section is not None and section[9] == 16, "missing ELF dynamic table")
    result = {}
    for tag, value in DYNAMIC.iter_unpack(image.section(".dynamic")):
        if tag == 0:
            return result
        result.setdefault(tag, []).append(value)
    raise ValueError("unterminated ELF dynamic table")


def load_provider(path):
    path = Path(path)
    provider = json.loads(path.read_text())
    require(provider.get("schema") == 1 and provider.get("format") == "ps5-native-runtime-sdk",
            f"unsupported provider manifest: {path}")
    require(isinstance(provider.get("module"), str) and
            re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", provider["module"]) is not None,
            "native provider identity must not contain path separators")
    require(provider["library"] == provider["module"] and
            provider["soname"] == provider["module"] + ".sprx",
            f"inconsistent provider identity: {path}")
    require(provider["module_version"] == 0x101 and provider["library_version"] == 1,
            f"unsupported provider version: {path}")
    library = path.parent / provider["import_library"]["path"]
    stub = library.read_bytes()
    require(hashlib.sha256(stub).hexdigest() ==
            provider["import_library"]["sha256"], f"provider import library hash mismatch: {path}")
    require(provider.get("linker_only") is True and provider.get("runtime_loadable") is False,
            f"expected linker-only SDK manifest: {path}")
    symbols = provider["symbols"]
    require(symbols and len({s["name"] for s in symbols}) == len(symbols),
            f"empty/duplicate provider symbols: {path}")
    for symbol in symbols:
        require(symbol["nid"] == nid(symbol["name"]), f"provider NID mismatch: {symbol['name']}")
    validate_stub(stub, {s["name"]: (0, s["info"], s["other"], 1, 0, s["size"])
                         for s in symbols}, provider["module"])
    return provider


def select_providers(source, providers):
    image = Elf(source)
    needed = [cstring(image.section(".dynstr"), offset)
              for offset in dynamic_entries(image).get(1, [])]
    declared = {p["soname"]: p for p in providers}
    require(len(declared) == len(providers), "duplicate provider SONAME")
    require(len(set(needed)) == len(needed), "duplicate source DT_NEEDED")
    require(set(needed) <= declared.keys(),
            f"undeclared source DT_NEEDED: {sorted(set(needed) - declared.keys())}")
    return [declared[name] for name in needed]


def convert(source, module, providers=(), *, process_lifetime=False):
    module_identity(module)
    require(isinstance(process_lifetime, bool), "process-lifetime contract must be boolean")
    image = Elf(source)
    require(image.kind == 3, "expected original LLD ET_DYN shared library")
    require(image.section_headers and ".dynsym" in image.sections,
            "shared library is missing section/symbol metadata")
    symbols = image.symbols(".dynsym")
    require(symbols and symbols[0] == ("", (0, 0, 0, 0, 0, 0)),
            "invalid shared-library null symbol")
    require(image.sections[".dynsym"][9] == SYM.size, "invalid dynamic symbol entry size")
    tags = dynamic_entries(image)
    lifecycle = dict(image.symbols(".symtab"))
    marker = lifecycle.get("__ps5_native_lifecycle_v1")
    has_crt = marker is not None
    if has_crt:
        require(marker[1] & 15 == 1 and marker[2] == 2 and marker[3] and
                marker[5] == len(LIFECYCLE_MARKER) and
                image.memory(marker[4], marker[5]) == LIFECYCLE_MARKER,
                "invalid native module CRT marker")
    lifetime = lifecycle.get("__ps5_native_process_lifetime_v1")
    if process_lifetime:
        require(has_crt and lifetime is not None and lifetime[1] & 15 == 1 and
                lifetime[2] == 2 and lifetime[3] and
                lifetime[5] == len(PROCESS_LIFETIME_MARKER) and
                image.memory(lifetime[4], lifetime[5]) == PROCESS_LIFETIME_MARKER,
                "process-lifetime contract requires a valid hidden marker and native CRT")
    else:
        require(lifetime is None, "module requires explicit process-lifetime contract")
    for tag in (25, 26, 32):
        size_tag = {25: 27, 26: 28, 32: 33}[tag]
        require(not any(tags.get(size_tag, [])) or has_crt and tag != 32,
                "constructor/destructor arrays require native_module_crt.cpp")
    require(not any(tags.get(22, [])) and 22 not in tags,
            "text relocations are unsupported")
    allocated = [(name, h) for name, h in image.sections.items() if h[2] & 2 and h[5]]
    for name, h in allocated:
        require(not h[2] & 0x400, f"native TLS requires qualified runtime support: {name}")
        require(h[1] == 8 or h[4] + h[5] <= len(source), f"truncated section: {name}")
        require(h[8] <= PAGE and (not h[8] or h[8] & (h[8] - 1) == 0),
                f"unsupported section alignment: {name}")
        require(not any(token in name for token in (".ctors", ".dtors", ".preinit_array")),
                "legacy/preinit constructor/destructor arrays are unsupported")
        require(not any(token in name for token in (".init_array", ".fini_array")) or has_crt,
                "constructor/destructor arrays require native_module_crt.cpp")
        require(h[1] in (1, 3, 4, 5, 6, 8, 11, 14, 15, 0x6FFFFFF6),
                f"unsupported allocated section type: {name}")
    loads = [p for p in image.phdrs if p[0] == 1]
    require(len(loads) == 4 and [p[1] for p in loads] == [5, 4, 6, 6],
            "link shared library with native-shared.ld (text/ro/relro/data LOADs)")
    text, ro, relro, data = loads
    require(text[3] == 0, "shared text must start at address zero")
    for p in loads:
        require(p[2] == p[3] + PAGE and p[3] % PAGE == 0 and p[7] == PAGE and
                p[5] <= p[6] and p[2] + p[5] <= len(source),
                "shared LOAD requires 16 KiB native layout and VA+0x4000 file offset")
    for left, right in zip(loads, loads[1:]):
        require(align(left[3] + left[6], PAGE) <= right[3], "overlapping shared LOAD pages")
    for name, h in allocated:
        require(sum(p[3] <= h[3] and h[3] + h[5] <= p[3] + p[6] and
                    (h[1] == 8 or h[4] - p[2] == h[3] - p[3]) for p in loads) == 1,
                f"allocated section outside its LOAD: {name}")
    params_section = image.sections.get(".ps5.module")
    require(params_section is not None and params_section[3] == relro[3] and
            params_section[5] == 0x2A8, "missing native-shared.ld module parameter reservation")
    dynamic_section = image.sections[".dynamic"]
    require(dynamic_section[3] == data[3] and dynamic_section[4] == data[2],
            "dynamic table must begin the writable LOAD")
    for name, tag in (("module_start", 12), ("module_stop", 13)):
        s = lifecycle.get(name)
        require(s is not None and s[3] and s[1] & 15 == 2 and
                tags.get(tag) == [s[4]] and text[3] <= s[4] < text[3] + text[5],
                f"missing defined lifecycle function or dynamic tag: {name}")
    if has_crt:
        for array in ("init", "fini"):
            h = image.sections.get("." + array + "_array")
            require(h is not None and h[5] % 8 == 0,
                    f"missing/invalid native CRT {array} array")
            for suffix, address in (("start", h[3]), ("end", h[3] + h[5])):
                s = lifecycle.get(f"__ps5_{array}_array_{suffix}")
                require(s is not None and s[4] == address and s[2] == 2,
                        f"native CRT {array} array boundary mismatch")
        frames = image.sections.get(".eh_frame")
        frame_symbol = lifecycle.get("__ps5_eh_frame_start")
        require(frames is not None and frames[5] >= 4 and frame_symbol is not None and
                frame_symbol[4] == frames[3] and
                image.section(".eh_frame")[-4:] == bytes(4),
                "native CRT requires a bounded zero-terminated .eh_frame section")
        require("__ps5_finalize_globals" in lifecycle and "__dso_handle" in lifecycle,
                "native CRT is missing DSO finalization")

    needed = [cstring(image.section(".dynstr"), offset) for offset in tags.get(1, [])]
    provider_map = {p["soname"]: p for p in providers}
    require(len(provider_map) == len(providers), "duplicate provider SONAME")
    require(len(set(needed)) == len(needed), "duplicate shared DT_NEEDED")
    require(set(needed) == set(provider_map),
            f"provider manifests must exactly cover DT_NEEDED: {needed}")
    order = [provider_map[name] for name in needed]
    strings = bytearray(b"\0")

    def string(value):
        offset = len(strings)
        strings.extend(value.encode() + b"\0")
        return offset

    module_offset, filename_offset = string(module), string(module + ".sprx")
    native_tags = []
    for index, provider in enumerate(order, 1):
        native_tags.extend((
            (1, string(provider["soname"])),
            (0x61000045, string(provider["module"]) |
             provider["module_version"] << 32 | index << 48),
            (0x61000049, string(provider["library"]) |
             provider["library_version"] << 32 | index << 48),
            (0x61000019, index << 48 | 9),
        ))
    encoded = bytearray(SYM.size)
    canonical = [""]
    seen = set()
    seen_nids = set()
    for name, s in symbols[1:]:
        require(name and name not in seen, f"empty/duplicate dynamic symbol: {name}")
        seen.add(name)
        require(nid(name) not in seen_nids, f"colliding dynamic symbol NID: {name}")
        seen_nids.add(nid(name))
        require(s[1] >> 4 in (1, 2) and s[1] & 15 in (0, 1, 2) and s[2] in (0, 3),
                f"unsupported symbol type/binding/visibility: {name}")
        if s[3]:
            identity, binding = module, "A#A"
            require(s[3] < len(image.section_headers) and
                    image.section_headers[s[3]][2] & 2,
                    f"export outside an allocated section: {name}")
        else:
            thread_destructor = name in ("__cxa_thread_atexit", "__cxa_thread_atexit_impl")
            require(not thread_destructor or process_lifetime,
                    "thread-local destructors require module-aware unload support")
            matches = [(i, p, next((e for e in p["symbols"] if e["name"] == name), None))
                       for i, p in enumerate(order, 1)]
            match = next((entry for entry in matches if entry[2] is not None), None)
            require(match is not None, f"no declared provider exports {name}")
            i, provider, export = match
            require(not thread_destructor or
                    provider["module"] == provider["library"] == "libkodi-runtime",
                    "process-lifetime TLS destructors must use the shared core")
            require(s[1] & 15 in (0, export["info"] & 15),
                    f"import/provider symbol type mismatch: {name}")
            require(not s[4] and (not s[5] or s[5] == export["size"]),
                    f"import/provider data size/value mismatch: {name}")
            identity = provider["module"]
            binding = encode_id(i) + "#" + encode_id(i)
        encoded.extend(SYM.pack(string(nid(name) + "#" + binding), s[1], s[2],
                                1 if s[3] else 0, s[4], s[5]))
        canonical.append(nid(name) + "#" + identity + "#" + identity)
    require(any(s[3] for _, s in symbols[1:]), "shared provider has no public exports")
    relocations = []
    for name, h in allocated:
        if h[1] != 4:
            continue
        require(name in (".rela.dyn", ".rela.plt") and h[9] == RELA.size,
                f"unsupported allocated relocation table: {name}")
        for offset, info, addend in RELA.iter_unpack(image.section(name)):
            kind, symbol = info & 0xFFFFFFFF, info >> 32
            # Bind all PLT slots eagerly through ordinary symbolic relocations.
            # No module-local lazy resolver or duplicate runtime dispatcher is needed.
            if kind == 7:
                kind = 6
            require(kind in SUPPORTED_RELOCATIONS and symbol < len(symbols),
                    f"unsupported dynamic relocation type/index: {kind}/{symbol}")
            require((kind == 8) == (symbol == 0), "invalid dynamic relocation symbol")
            require(any(p[1] & 2 and p[3] <= offset and offset + 8 <= p[3] + p[6]
                        for p in loads), "dynamic relocation targets non-writable memory")
            relocations.append((offset, symbol << 32 | kind, addend))
    targets = [r[0] for r in relocations]
    require(len(set(targets)) == len(targets), "duplicate input dynamic relocation target")
    if has_crt:
        finalizer = lifecycle["__ps5_finalize_globals"][4]
        fini = image.sections[".fini_array"]
        require(fini[5] >= 8 and (fini[3], 8, finalizer) in relocations,
                "native CRT finalizer must be the first fini-array entry")
    param_va = relro[3]
    params = bytearray(0x2A8)
    struct.pack_into("<QIIIIII", params, 24, 32, 0x3C13F4BF, 3,
                     0x08050001, 0x02000009, 1, 0)
    for offset, size, revision in ((0x38, 0xA8, 0x10000000E), (0xE0, 0x38, 0),
                                  (0x118, 0x10, 0), (0x128, 0x78, 2),
                                  (0x1A0, 0xC0, 3), (0x260, 0x38, 1)):
        struct.pack_into("<QQ", params, offset, size, revision)
    struct.pack_into("<QQ", params, 0x298, 0xFFFFFFFFFFFFFFFF, 1)
    generated = [(param_va + target, 8, param_va + value)
                 for target, value in ((0x50, 0x38), (0x58, 0xE0), (0x60, 0x118),
                                       (0x68, 0x128), (0x70, 0x1A0), (0x98, 0x260),
                                       (0x48, 0x298), (0x58, 0x2A0))]
    require(not any(param_va <= t < param_va + len(params) for t in targets),
            "input relocation overlaps native parameters")
    relative = generated + [r for r in relocations if r[1] == 8]
    symbolic = [r for r in relocations if r[1] != 8]
    meta_va = align(data[3] + data[6], 16)
    metadata = bytearray()

    def append(blob):
        metadata.extend(bytes(align(len(metadata)) - len(metadata)))
        address = meta_va + len(metadata)
        metadata.extend(blob)
        return address

    str_va, sym_va = append(strings), append(encoded)
    rel_blob = b"".join(RELA.pack(*r) for r in relative + symbolic)
    rel_va = append(rel_blob)
    hashed = hash_table(canonical)
    hash_va = append(hashed)
    note_va = append(NOTE_HEADER + bytes(20))
    native_tags.extend((
        (0x61000043, module_offset | 0x101 << 32), (0x61000011, 0),
        (0x61000041, filename_offset),
        (0x61000047, module_offset | 1 << 32), (0x61000017, 1), (21, 0),
        (7, rel_va), (8, len(rel_blob)), (9, RELA.size), (0x6FFFFFF9, len(relative)),
        (23, rel_va), (2, 0), (3, param_va), (20, 7),
        (6, sym_va), (11, SYM.size), (5, str_va), (10, len(strings)), (4, hash_va),
        (12, tags[12][0]), (13, tags[13][0]),
        (0x6100003F, len(encoded)), (0x6100003D, len(hashed)), (0, 0),
    ))
    native_dynamic = b"".join(DYNAMIC.pack(*entry) for entry in native_tags)
    # Native compact loading resolves PT_DYNAMIC through the flags-zero metadata LOAD.
    dynamic_va = append(native_dynamic)
    struct.pack_into("<Q", params, 0, dynamic_va)
    raw = bytearray(PAGE + meta_va + len(metadata))
    for p in loads:
        raw[p[2]:p[2] + p[5]] = source[p[2]:p[2] + p[5]]
    raw[params_section[4]:params_section[4] + len(params)] = params
    raw[dynamic_section[4]:dynamic_section[4] + dynamic_section[5]] = bytes(dynamic_section[5])
    raw[PAGE + meta_va:] = metadata
    comment_text = (module + ".sprx\0").encode()
    comment = bytearray(align(12 + len(comment_text), 4))
    struct.pack_into("<4sII", comment, 0, b"PATH", len(comment) - 8, len(comment_text))
    comment[12:12 + len(comment_text)] = comment_text
    version = (bytes.fromhex("0000160008") + b"crt1:" +
               struct.pack(">IIII", 0x02000009, 1, 0x02000009, 1))
    comment_file = align(len(raw), 16)
    version_file = align(comment_file + len(comment), 16)
    tail_file = align(version_file + len(version), 16)
    raw.extend(bytes(tail_file + 24 - len(raw)))
    raw[comment_file:comment_file + len(comment)] = comment
    raw[version_file:version_file + len(version)] = version
    headers = [
        [1, 1, text[2], text[3], text[3], text[5], text[6], PAGE],
        [1, 4, ro[2], ro[3], ro[3], ro[5], ro[6], PAGE],
        [1, 6, relro[2], relro[3], relro[3], relro[5], relro[6], PAGE],
        [0x6474E552, 4, relro[2], relro[3], relro[3], relro[5], align(relro[6], PAGE), 1],
        list(data),
        [0x61000002, 4, PAGE + param_va + 24, param_va + 24, param_va + 24, 32, 32, 8],
        [7, 4, relro[2], relro[3], relro[3], 0, 0, 1],
    ]
    eh = image.sections.get(".eh_frame_hdr")
    if eh and eh[5]:
        headers.append([0x6474E550, 4, eh[4], eh[3], eh[3], eh[5], eh[5], 4])
    headers.extend((
        [1, 0, PAGE + meta_va, meta_va, meta_va, len(metadata), len(metadata), PAGE],
        [4, 0, PAGE + note_va, note_va, note_va, len(NOTE_HEADER) + 20,
         len(NOTE_HEADER) + 20, 4],
        [2, 6, PAGE + dynamic_va, dynamic_va, dynamic_va,
         len(native_dynamic), len(native_dynamic), 8],
        [0x6FFFFF00, 0, comment_file, 0, 0, len(comment), 0, 16],
        [0x6FFFFF01, 0, version_file, 0, 0, len(version), len(version), 1],
        [4, 0, tail_file, 0, 0, 24, 0, 4],
    ))
    require(64 + len(headers) * PHDR.size <= PAGE, "too many native program headers")
    raw[:64] = struct.pack("<16sHHIQQQIHHHHHH",
                           b"\x7fELF\x02\x01\x01\x09\x02" + bytes(7),
                           0xFE18, 62, 1, 0, 64, 0, 0, 64, PHDR.size, len(headers), 64, 0, 0)
    for index, header in enumerate(headers):
        PHDR.pack_into(raw, 64 + index * PHDR.size, *header)
    raw[PAGE + note_va + 16:PAGE + note_va + 32] = hashlib.sha1(raw).digest()[:16]
    return bytes(raw)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--module", required=True)
    parser.add_argument("--provider", action="append", default=[], type=Path)
    args = parser.parse_args()
    try:
        output = convert(args.input.read_bytes(), args.module,
                         [load_provider(path) for path in args.provider])
        with args.output.open("xb") as stream:
            stream.write(output)
    except (OSError, ValueError, KeyError, IndexError, struct.error) as error:
        parser.exit(1, f"native-shared-link: {error}\n")


if __name__ == "__main__":
    main()
